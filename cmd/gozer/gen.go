// span says gen[gen:gen+n] is a verbatim copy of src[src:src+n].
type span struct{ src, gen, n int }

// tagInfo locates a start tag; probe is where "_pN." ends in gen for components (-1 otherwise).
type tagInfo struct {
	tag         string
	start, head int
	probe       int
}

// output is generated Go before gofmt, with the map back to the template.
type output struct {
	gen   string
	spans []span
	tags  []tagInfo
	marks []mark
}

type gen struct {
	b       strings.Builder
	n       int
	path    string
	runtime string
	local   map[string]bool // components declared by .gozer files in this package
	editor  bool            // tolerate broken Go and emit completion probes
	dotAt   int
	out     output
}

// builtins are runtime components usable without the gozer. prefix.
var builtins = map[string]bool{"Router": true, "NavLink": true, "PageTitle": true,
	"CascadingValue": true, "ErrorBoundary": true, "AuthorizeView": true, "HeadContent": true}

func (g *gen) p(format string, args ...any) { fmt.Fprintf(&g.b, format, args...) }

// src copies template Go code into the output and records where it went.
func (g *gen) src(s goSrc) {
	g.out.spans = append(g.out.spans, span{s.pos, g.b.Len(), len(s.code)})
	g.b.WriteString(s.code)
}

func (g *gen) tmp(prefix string) string {
	g.n++
	return fmt.Sprintf("_%s%d", prefix, g.n)
}

type genError struct {
	line int
	msg  string
}

func (e *genError) Error() string { return e.msg }

func (g *gen) fail(line int, format string, args ...any) {
	panic(&genError{line, fmt.Sprintf("%s:%d: %s", g.path, line, fmt.Sprintf(format, args...))})
}

// generate turns a parsed template into Go source. The result is not gofmt'ed
// so that spans stay valid; the CLI formats it before writing.
func generate(path, pkg, runtime string, local map[string]bool, f *file, editor bool, dotAt int) (out *output, err error) {
	g := &gen{path: path, runtime: runtime, local: local, editor: editor, dotAt: dotAt}
	g.out.marks = f.marks
	defer func() {
		if r := recover(); r != nil {
			ge, ok := r.(*genError)
			if !ok {
				panic(r)
			}
			out, err = nil, ge
		}
	}()
	var codes []string
	for _, c := range f.code {
		codes = append(codes, c.code)
	}
	typeParams, declared, err := findType(strings.Join(codes, "\n\n"), f.name)
	if err != nil && !editor {
		return nil, fmt.Errorf("%s: @code: %w", path, err)
	}
	if declared && (len(f.params) > 0 || len(f.injects) > 0) {
		return nil, fmt.Errorf("%s: @param/@inject only work when @code does not declare type %s; add the fields to the struct instead", path, f.name)
	}
	if len(f.pages) > 0 && typeParams != "" {
		return nil, fmt.Errorf("%s: a generic component cannot be a @page", path)
	}
	if editor {
		// not the "DO NOT EDIT" marker: gopls warns on every change to a generated file
		g.p("// Editor copy of %s, generated by gozer.\n\n", baseName(path))
	} else {
		g.p("// Code generated by gozer from %s. DO NOT EDIT.\n\n", baseName(path))
	}
	g.p("package %s\n\nimport (\n\tgozer %q\n", pkg, runtime)
	for _, imp := range f.imports {
		g.p("\t")
		g.src(imp)
		g.p("\n")
	}
	g.p(")\n\n")
	for _, c := range f.code {
		g.src(c)
		g.p("\n\n")
	}
	if !declared {
		g.p("type %s struct {\n\t", f.name)
		if f.inherits.code != "" {
			g.src(f.inherits)
		} else {
			g.p("gozer.Base")
		}
		g.p("\n")
		for _, pr := range f.params {
			g.p("\t")
			g.src(pr)
			g.p("\n")
		}
		for _, in := range f.injects {
			g.p("\t")
			g.src(in)
			g.p(" `inject:\"\"`\n")
		}
		g.p("}\n\n")
	}
	if len(f.pages) > 0 {
		g.p("func init() {\n")
		for _, r := range f.pages {
			g.p("\tgozer.RegisterPage(%q, func() gozer.Component { return &%s{} }, ", r, f.name)
			if f.layout.code != "" {
				g.p("func() gozer.Component { return &")
				g.src(f.layout)
				g.p("{} })\n")
			} else {
				g.p("nil)\n")
			}
		}
		g.p("}\n\n")
	}
	g.p("func (c *%s%s) Render() gozer.Node {\n\tvar _n0 []gozer.Node\n", f.name, typeParams)
	g.nodes(f.body, "_n0")
	g.p("\treturn gozer.Frag(_n0...)\n}\n")
	g.out.gen = g.b.String()
	return &g.out, nil
}

func baseName(path string) string { return path[strings.LastIndexAny(path, `/\`)+1:] }

// findType reports whether code declares type name, and its type parameter list for a receiver.
// A partial answer comes back alongside a syntax error.
func findType(code, name string) (typeParams string, declared bool, err error) {
	if strings.TrimSpace(code) == "" {
		return "", false, nil
	}
	fset := token.NewFileSet()
	af, err := parser.ParseFile(fset, "", "package x\n"+code, parser.SkipObjectResolution)
	if af == nil {
		return "", false, err
	}
	for _, d := range af.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, s := range gd.Specs {
			ts := s.(*ast.TypeSpec)
			if ts.Name.Name != name {
				continue
			}
			if ts.TypeParams == nil {
				return "", true, err
			}
			var names []string
			for _, f := range ts.TypeParams.List {
				for _, n := range f.Names {
					names = append(names, n.Name)
				}
			}
			return "[" + strings.Join(names, ", ") + "]", true, err
		}
	}
	return "", false, err
}

func significant(n node) bool {
	t, ok := n.(textN)
	return !ok || strings.TrimSpace(t.s) != ""
}

func (g *gen) nodes(list []node, slice string) {
	for _, n := range list {
		g.node(n, slice)
	}
}

func (g *gen) node(n node, slice string) {
	switch v := n.(type) {
	case textN:
		if strings.TrimSpace(v.s) == "" && strings.Contains(v.s, "\n") {
			return
		}
		g.p("%s = append(%s, gozer.Text(%s))\n", slice, slice, strconv.Quote(v.s))
	case rawN:
		g.p("%s = append(%s, gozer.Raw(%s))\n", slice, slice, strconv.Quote(v.s))
	case exprN:
		g.p("%s = append(%s, gozer.X(", slice, slice)
		g.src(v.goSrc)
		g.p("))\n")
	case codeN:
		g.src(v.goSrc)
		g.p("\n")
	case ifN:
		for i, cond := range v.conds {
			switch {
			case i == 0:
				g.p("if ")
			case cond.pos < 0:
				g.p("} else {\n")
			default:
				g.p("} else if ")
			}
			if cond.pos >= 0 {
				g.src(cond)
				g.p(" {\n")
			}
			g.nodes(v.bodies[i], slice)
		}
		g.p("}\n")
	case forN:
		g.p("for ")
		g.src(v.clause)
		g.p(" {\n")
		g.nodes(v.body, slice)
		g.p("}\n")
	case elemN:
		if isComponent(v.tag) {
			g.component(v, slice)
		} else {
			g.element(v, slice)
		}
	default:
		panic(fmt.Sprintf("unknown node %T", n))
	}
}

func isComponent(tag string) bool {
	return tag != "" && (strings.HasPrefix(tag, ":") || strings.Contains(tag, ".") || unicode.IsUpper(rune(tag[0])))
}

// value writes an attribute value as a Go expression.
func (g *gen) value(line int, a attrN) {
	if !a.has {
		g.p("true")
		return
	}
	parts, err := interp(g.path, a.raw, a.rawPos, g.dotAt)
	if err != nil {
		g.fail(line, "attribute %s: %v", a.name, err)
	}
	switch {
	case len(parts) == 0:
		g.p(`""`)
		return
	case len(parts) == 1 && parts[0].text == "":
		g.exprPart(parts[0].expr)
		return
	case len(parts) == 1:
		g.p("%s", strconv.Quote(a.raw))
		return
	}
	g.p("gozer.S(")
	for i, pt := range parts {
		if i > 0 {
			g.p(", ")
		}
		if pt.text != "" {
			g.p("%s", strconv.Quote(pt.text))
		} else {
			g.exprPart(pt.expr)
		}
	}
	g.p(")")
}

// exprPart writes an @expression from an attribute value; the '@' before it is template syntax.
func (g *gen) exprPart(e goSrc) {
	g.out.marks = append(g.out.marks, mark{e.pos - 1, 1, false})
	g.src(e)
}

func hasAttr(el elemN, name string) bool {
	for _, a := range el.attrs {
		if a.name == name {
			return true
		}
	}
	return false
}

// code is a directive attribute's value: Go code, optionally prefixed with '@'.
func code(a attrN) goSrc {
	t := strings.TrimLeft(a.raw, " \t\r\n")
	pos := a.rawPos + len(a.raw) - len(t)
	t = strings.TrimRight(t, " \t\r\n")
	if strings.HasPrefix(t, "@") {
		t, pos = t[1:], pos+1
	}
	return goSrc{t, pos}
}

func (g *gen) element(el elemN, slice string) {
	g.out.tags = append(g.out.tags, tagInfo{el.tag, el.start, el.head, -1})
	v := g.tmp("n")
	g.p("{\nvar %s []gozer.Node\n", v)
	mods := map[string][]string{} // directive -> extra options
	for _, a := range el.attrs {
		base, mod, ok := strings.Cut(a.name, ":")
		if !ok || !strings.HasPrefix(base, "@") {
			continue
		}
		switch mod {
		case "preventDefault":
			mods[base] = append(mods[base], "gozer.Prevent")
		case "stopPropagation":
			mods[base] = append(mods[base], "gozer.Stop")
		case "event":
			mods[base] = append(mods[base], fmt.Sprintf("gozer.BindEvent(%s)", strconv.Quote(a.raw)))
		case "format":
			mods[base] = append(mods[base], fmt.Sprintf("gozer.BindFormat(%s)", strconv.Quote(a.raw)))
		default:
			g.fail(el.line, "unknown modifier %s", a.name)
		}
	}
	opts := func(name string) string {
		return strings.Join(append([]string{"gozer.OwnedBy(c)"}, mods[name]...), ", ")
	}
	for _, a := range el.attrs {
		name := a.name
		if strings.Contains(name, ":") && strings.HasPrefix(name, "@") {
			base, _, _ := strings.Cut(name, ":")
			if strings.HasPrefix(base, "@on") && !hasAttr(el, base) { // e.g. <form @onsubmit:preventDefault>
				g.p("%s = append(%s, gozer.On(%q, func() {}, %s))\n", v, v, base[3:], strings.Join(mods[base], ", "))
				mods[base] = nil
			}
			continue
		}
		g.p("%s = append(%s, ", v, v)
		switch {
		case name == "@bind" || name == "@bind-value":
			g.p("gozer.Bind(&(")
			g.src(code(a))
			g.p("), %s)", opts(name))
		case strings.HasPrefix(name, "@on"):
			if !a.has {
				g.fail(el.line, "%s needs a handler", name)
			}
			g.p("gozer.On(%q, ", name[3:])
			g.src(code(a))
			g.p(", %s)", opts(name))
		case name == "@key":
			g.p("gozer.Key(")
			g.src(code(a))
			g.p(")")
		case name == "@ref":
			g.p("gozer.Ref(&(")
			g.src(code(a))
			g.p("))")
		case name == "@attributes":
			g.p("gozer.Attrs(")
			g.src(code(a))
			g.p(")")
		case strings.HasPrefix(name, "@"):
			g.fail(el.line, "unknown directive %s on <%s>", name, el.tag)
		default:
			g.p("gozer.Attr(%q, ", name)
			g.value(el.line, a)
			g.p(")")
		}
		g.p(")\n")
	}
	g.nodes(el.kids, v)
	g.p("%s = append(%s, gozer.El(%q, %s...))\n}\n", slice, slice, el.tag, v)
}

func (g *gen) component(el elemN, slice string) {
	if strings.HasPrefix(el.tag, ":") {
		g.fail(el.line, "<%s> is only allowed directly inside a component", el.tag)
	}
	p := g.tmp("p")
	g.p("%s = append(%s, ", slice, slice)
	var key *attrN
	for i, a := range el.attrs {
		if a.name == "@key" {
			key = &el.attrs[i]
			g.p("gozer.Keyed(")
			g.src(code(a))
			g.p(", ")
		}
	}
	g.p("gozer.C(func(%s *", p)
	if base, _, _ := strings.Cut(el.tag, "["); builtins[base] && !g.local[base] {
		g.p("gozer.")
	}
	g.src(goSrc{el.tag, el.tagPos})
	g.p(") {\n")
	probe := -1
	if g.editor {
		g.p("_ = %s.", p)
		probe = g.b.Len()
		g.p("Render\n")
	}
	g.out.tags = append(g.out.tags, tagInfo{el.tag, el.start, el.head, probe})
	for _, a := range el.attrs {
		switch name := a.name; {
		case name == "@key":
		case name == "@ref":
			g.src(code(a))
			g.p(" = %s\n", p)
		case strings.HasPrefix(name, "@bind-"):
			g.p("%s.", p)
			g.src(goSrc{name[6:], a.namePos + 6})
			g.p(" = gozer.BindTo(&(")
			g.src(code(a))
			g.p("), c)\n")
		case strings.HasPrefix(name, "@"):
			g.fail(el.line, "unknown directive %s on component <%s>", name, el.tag)
		case len(name) > 2 && strings.HasPrefix(name, "On") && unicode.IsUpper(rune(name[2])) && a.has:
			g.p("%s.", p)
			g.src(goSrc{name, a.namePos})
			g.p(" = gozer.Callback(c, ")
			g.value(el.line, a)
			g.p(")\n")
		default:
			g.p("%s.", p)
			g.src(goSrc{name, a.namePos})
			g.p(" = ")
			g.value(el.line, a)
			g.p("\n")
		}
	}
	var rest []node
	for _, k := range el.kids {
		frag, ok := k.(elemN)
		if !ok || !strings.HasPrefix(frag.tag, ":") {
			rest = append(rest, k)
			continue
		}
		g.fragment(p, goSrc{frag.tag[1:], frag.tagPos + 1}, frag)
	}
	for _, k := range rest {
		if significant(k) {
			g.fragment(p, goSrc{"ChildContent", -1}, elemN{kids: rest, line: el.line})
			break
		}
	}
	g.p("})")
	if key != nil {
		g.p(")")
	}
	g.p(")\n")
}

func (g *gen) fragment(p string, field goSrc, el elemN) {
	var args *attrN
	for i, a := range el.attrs {
		if a.name != "args" {
			g.fail(el.line, "<:%s> only takes an args attribute", field.code)
		}
		args = &el.attrs[i]
	}
	setField := func() {
		g.p("%s.", p)
		if field.pos >= 0 {
			g.src(field)
		} else {
			g.p("%s", field.code)
		}
		g.p(" = ")
	}
	v := g.tmp("n")
	if args != nil {
		setField()
		g.p("func(")
		g.src(goSrc{args.raw, args.rawPos})
		g.p(") gozer.Node {\nvar %s []gozer.Node\n", v)
		g.nodes(el.kids, v)
		g.p("return gozer.Frag(%s...)\n}\n", v)
		return
	}
	g.p("{\nvar %s []gozer.Node\n", v)
	g.nodes(el.kids, v)
	setField()
	g.p("gozer.Frag(%s...)\n}\n", v)
}
