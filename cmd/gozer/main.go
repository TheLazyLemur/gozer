// Command gozer compiles .gozer templates into Go components.
//
//	//go:generate go run github.com/TheLazyLemur/gozer/cmd/gozer
//
// Each Name.gozer becomes Name.gozer.go in the same package.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

const header = "// Code generated by gozer from "

func main() {
	if len(os.Args) > 1 && os.Args[1] == "lsp" {
		if err := runLSP(os.Args[2:]); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		return
	}
	runtime := flag.String("runtime", "github.com/TheLazyLemur/gozer", "import path of the gozer runtime package")
	flag.Usage = func() {
		fmt.Fprintln(os.Stderr, "usage: gozer [-runtime path] [dir ...]   compile templates (default: current directory, recursive)")
		fmt.Fprintln(os.Stderr, "       gozer lsp [-gopls path] [-runtime path]   language server for editors")
		flag.PrintDefaults()
	}
	flag.Parse()
	dirs := flag.Args()
	if len(dirs) == 0 {
		dirs = []string{"."}
	}
	failed := false
	for _, d := range dirs {
		if err := compileTree(d, *runtime); err != nil {
			fmt.Fprintln(os.Stderr, err)
			failed = true
		}
	}
	if failed {
		os.Exit(1)
	}
}

func compileTree(root, runtime string) error {
	var errs []string
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		name := d.Name()
		if d.IsDir() {
			if path != root && (strings.HasPrefix(name, ".") || name == "vendor" || name == "node_modules" || name == "testdata") {
				return filepath.SkipDir
			}
			return nil
		}
		switch {
		case strings.HasSuffix(name, ".gozer"):
			if err := compileFile(path, runtime); err != nil {
				errs = append(errs, err.Error())
			}
		case strings.HasSuffix(name, ".gozer.go"):
			removeOrphan(path)
		}
		return nil
	})
	if err != nil {
		return err
	}
	if len(errs) > 0 {
		return fmt.Errorf("%s", strings.Join(errs, "\n"))
	}
	return nil
}

// removeOrphan deletes generated files whose .gozer source is gone.
func removeOrphan(path string) {
	if _, err := os.Stat(strings.TrimSuffix(path, ".go")); err == nil {
		return
	}
	data, err := os.ReadFile(path)
	if err == nil && bytes.HasPrefix(data, []byte(header)) {
		os.Remove(path)
	}
}

func compileFile(path, runtime string) error {
	src, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	name := strings.TrimSuffix(filepath.Base(path), ".gozer")
	if !token.IsIdentifier(name) {
		return fmt.Errorf("%s: file name must be a Go identifier (it names the component type)", path)
	}
	f, err := parse(path, name, string(src))
	if err != nil {
		return err
	}
	out, err := generate(path, packageName(filepath.Dir(path)), runtime, localComponents(filepath.Dir(path)), f, false, -1)
	if err != nil {
		return err
	}
	formatted, err := format.Source([]byte(out.gen))
	if err != nil {
		formatted = []byte(out.gen) // keep it on disk so the compiler error can be read
		err = fmt.Errorf("%s: generated code does not parse: %v", path, err)
	}
	target := path + ".go"
	if old, rerr := os.ReadFile(target); rerr != nil || !bytes.Equal(old, formatted) {
		if werr := os.WriteFile(target, formatted, 0o644); werr != nil {
			return werr
		}
	}
	return err
}

func localComponents(dir string) map[string]bool {
	names := map[string]bool{}
	matches, _ := filepath.Glob(filepath.Join(dir, "*.gozer"))
	for _, m := range matches {
		names[strings.TrimSuffix(filepath.Base(m), ".gozer")] = true
	}
	return names
}

// packageName reads the package clause of a hand-written Go file in dir,
// falling back to the directory name.
func packageName(dir string) string {
	entries, _ := os.ReadDir(dir)
	for _, e := range entries {
		n := e.Name()
		if !strings.HasSuffix(n, ".go") || strings.HasSuffix(n, "_test.go") || strings.HasSuffix(n, ".gozer.go") {
			continue
		}
		f, err := parser.ParseFile(token.NewFileSet(), filepath.Join(dir, n), nil, parser.PackageClauseOnly)
		if err == nil {
			return f.Name.Name
		}
	}
	abs, _ := filepath.Abs(dir)
	name := strings.Map(func(r rune) rune {
		if r == '-' || r == '.' {
			return '_'
		}
		return r
	}, strings.ToLower(filepath.Base(abs)))
	return name
}
